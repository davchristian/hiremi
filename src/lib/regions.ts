const US_STATE_CODE =
  /,\s*(?:AL|AK|AZ|AR|CA|CO|CT|DE|FL|GA|HI|IL|IN|IA|KS|KY|LA|ME|MD|MA|MI|MN|MS|MO|MT|NE|NV|NH|NJ|NM|NY|NC|ND|OH|OK|OR|PA|RI|SC|SD|TN|TX|UT|VT|VA|WA|WV|WI|WY|DC)\b/;

function wordPattern(terms: readonly string[]): RegExp {
  return new RegExp(`(?<![\\w])(?:${terms.join("|")})(?![\\w])`, "i");
}

const PATTERNS: [Region, RegExp][] = [
  ["indonesia", wordPattern(INDONESIA_TERMS)],
  ["singapore", wordPattern(["singapore", "singapura"])],
  ["asia_other", wordPattern(ASIA_OTHER_TERMS)],
];

const OTHER_PATTERN = wordPattern(OTHER_TERMS.filter((term) => term !== "us" && term !== "uk" && term !== "eu"));
const SHORT_OTHER_PATTERN = /(?<![\w.])(?:US|UK|EU)(?![\w.])/;

