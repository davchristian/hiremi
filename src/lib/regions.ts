export function regionOfCountryCode(code: string): Region {
  return ISO_REGIONS[code.trim().toLowerCase()] ?? "other";
}

export function regionsIn(text: string): Region[] {
  const found = new Set<Region>();
  for (const [region, pattern] of PATTERNS) {
    if (pattern.test(text)) found.add(region);
  }
  if (OTHER_PATTERN.test(text) || SHORT_OTHER_PATTERN.test(text) || US_STATE_CODE.test(text)) {
    found.add("other");
  }
  return [...found];
}

